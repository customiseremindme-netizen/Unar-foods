// Combines every migration into ONE file that can be pasted into the
// Supabase SQL Editor (for owners who don't use a terminal).
// Run: npm run db:bundle   (a unit test fails if the bundle is out of date)
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "supabase", "migrations");
const out = path.join(root, "supabase", "setup", "all-migrations.sql");

export function buildBundle() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  const header = `-- =============================================================================
-- UNAR — complete database setup (generated from supabase/migrations).
-- Paste this WHOLE file into Supabase → SQL Editor → New query → Run, ONCE,
-- on a brand-new project. Do not edit this file by hand: run
-- \`npm run db:bundle\` after changing a migration.
-- Files included: ${files.join(", ")}
-- =============================================================================
`;
  return header + files.map((f) => `\n-- >>> ${f}\n${fs.readFileSync(path.join(dir, f), "utf8").trimEnd()}\n`).join("");
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, buildBundle());
  console.log(`Wrote ${path.relative(root, out)}`);
}
